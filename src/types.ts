export interface Variant {
  /** "<language>-<level>", e.g. "it-beginner". Key into Paragraph.explanations. */
  key: string;
  language: string;
  level: "beginner" | "intermediate" | "expert";
  /** Human-readable label for the selector, e.g. "Italiano · Nessun background". */
  label: string;
}

export interface LibraryEntry {
  slug: string;
  title: string;
  authors: string[];
  importedAt: string;
  language: string;
  background: string;
  pageCount: number;
  variants: Variant[];
  /** Plain-language summary of the whole paper, keyed by language ("it", "en"): always written for a reader with no background, whatever the variants' levels. */
  tldr?: Record<string, Tldr>;
}

/** The paper in brief: fixed fields so every paper's summary reads the same way. */
export interface Tldr {
  /** What doesn't work today, with an everyday analogy rather than jargon. */
  problem: string;
  /** What the authors propose. */
  idea: string;
  /** What they get, numbers made tangible. */
  result: string;
  /** Who it matters to, and what it leaves open. */
  why?: string;
}

export interface PaperMeta extends LibraryEntry {
  sourceType: "arxiv" | "url" | "local";
  sourceRef: string;
  sourceVersion?: string;
  sourceSha256?: string;
}

export interface ParagraphAnchor {
  /** Zero-based PDF page; the rectangles belong to this page. */
  page: number;
  rects: [number, number, number, number][];
}

export interface Paragraph {
  id: string;
  page: number;
  order: number;
  section?: string;
  /** Fractions of page width/height (0-1), top-left origin. */
  rects: [number, number, number, number][];
  /** Logical passage across pages. Legacy page/rects mirror the first anchor. */
  anchors?: ParagraphAnchor[];
  sourceText: string;
  /** Keyed by Variant.key ("<language>-<level>"). */
  explanations: Record<string, string>;
  notebookSuggestion?: string;
  /**
   * Optional long-form explanation for dense paragraphs, keyed by Variant.key: markdown with
   * `$…$`/`$$…$$` math and `[text](#<paragraphId>)` links to other paragraphs. Shown collapsed
   * under the note ("Approfondisci").
   */
  deepDive?: Record<string, string>;
  /** Recall questions about this paragraph, written at import; question and answer keyed by Variant.key. */
  recall?: RecallQuestion[];
  /**
   * For set-up paragraphs whose point only shows later: where in the paper this gets used
   * ("Servirà più avanti"), in reading order.
   */
  leadsTo?: ForwardLink[];
}

export interface ForwardLink {
  /** A later paragraph's id. */
  to: string;
  /** What this paragraph contributes there, keyed by Variant.key. */
  why: Record<string, string>;
}

export interface RecallQuestion {
  /** Unique within the paragraph, e.g. "r1". */
  id: string;
  q: Record<string, string>;
  a: Record<string, string>;
}

export type AnnotationTool = "none" | "text" | "draw" | "erase";

interface AnnotationBase {
  id: string;
  page: number;
  color: string;
  createdAt: string;
  updatedAt?: string;
}

export interface TextAnnotation extends AnnotationBase {
  type: "text";
  /** Fractions of page width/height (0-1), top-left origin. */
  x: number;
  y: number;
  text: string;
}

export interface FreehandAnnotation extends AnnotationBase {
  type: "freehand";
  /** Fractions of page width/height (0-1), top-left origin. */
  points: [number, number][];
  strokeWidth: number;
}

export type Annotation = TextAnnotation | FreehandAnnotation;

/** One entry of `papers/<slug>/concepts.json`: a term or symbol the paper relies on. */
export interface Concept {
  id: string;
  term: string;
  /** Other spellings to match in explanation text (plurals, inflections, English forms). */
  aliases: string[];
  kind: "term" | "symbol" | "acronym";
  /** Paragraph id where the paper introduces it. */
  definedIn: string;
  /** Spellings as they appear in the PDF itself (usually English), for highlighting it there. Defaults to term + aliases. */
  pdfTerms?: string[];
  /** Keyed by Variant.key, like Paragraph.explanations. */
  definitions: Record<string, string>;
  related: string[];
}

/** One paper's entry for a concept in `papers/concepts-index.json` (generated by scripts/build-concepts-index.mjs). */
export interface ConceptIndexEntry {
  slug: string;
  title: string;
  term: string;
  definedIn: string;
  /** The definition for that paper's first variant. */
  definition: string;
}

/** Concept id → every paper that defines it. Ids are shared across papers for the same concept. */
export type ConceptsIndex = Record<string, ConceptIndexEntry[]>;

/** One claim of the paper's argument (`papers/<slug>/structure.json`). */
export interface ArgumentClaim {
  id: string;
  /** Short statement of the claim, keyed by Variant.key. */
  title: Record<string, string>;
  /** One or two sentences on what the claim says and why it matters, keyed by Variant.key. */
  summary: Record<string, string>;
  /** Paragraphs where the paper states the claim. */
  statedIn: string[];
  /** Paragraphs that support it: methods, derivations, results. */
  evidence: string[];
  /** Other claims this one builds on. */
  dependsOn: string[];
}

/** The argument map of a paper: its thesis and the claims that carry it. */
export interface PaperStructure {
  thesis: Record<string, string>;
  claims: ArgumentClaim[];
  /** Optional section guides: what the objects mean and why each passage is here. */
  readingGuide?: ReadingSection[];
}

export interface ReadingSection {
  id: string;
  title: Record<string, string>;
  /** What the reader should understand by the end of this section. */
  goal: Record<string, string>;
  steps: ReadingStep[];
  /** The passage that uses what this section has established. */
  leadsTo?: { paragraphId: string; why: Record<string, string> };
}

export interface ReadingStep {
  id: string;
  title: Record<string, string>;
  /** Paragraphs covered by this step, in reading order, including continuations/captions. */
  paragraphs: string[];
  /** What the objects correspond to: physical arrangement, logical operation, metric, etc. */
  meaning: Record<string, string>;
  /** Optional explanatory image in public/, with a caption at each reading level. */
  diagram?: { path: string; caption: Record<string, string> };
  /** Why this passage is needed in the section's argument. */
  purpose: Record<string, string>;
}
